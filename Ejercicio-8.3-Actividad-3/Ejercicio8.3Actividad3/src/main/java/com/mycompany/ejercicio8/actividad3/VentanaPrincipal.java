    private void agregarNuevasFiguras() {
        javax.swing.JButton cubo = new javax.swing.JButton("Cubo");
        javax.swing.JButton prisma = new javax.swing.JButton("Prisma");
        for (javax.swing.JButton b : new javax.swing.JButton[]{cubo, prisma}) {
            b.setBackground(new java.awt.Color(233, 248, 248));
            b.setPreferredSize(new java.awt.Dimension(87, 32));
        }
        cubo.addActionListener(evt -> {
            VentanaCubo ventanaCubo = new VentanaCubo(); /* Crea la ventana del cubo */
            ventanaCubo.setVisible(true);
        });
        prisma.addActionListener(evt -> {
            VentanaPrisma ventanaPrisma = new VentanaPrisma(); /* Crea la ventana del prisma */
            ventanaPrisma.setVisible(true);
        });

        javax.swing.JPanel filaNueva = new javax.swing.JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.CENTER, 40, 0));
        filaNueva.add(cubo);
        filaNueva.add(prisma);

        javax.swing.JPanel botonesOriginales = (javax.swing.JPanel) getContentPane();
        javax.swing.JPanel contenedor = new javax.swing.JPanel(new java.awt.BorderLayout());
        contenedor.setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 0, 40, 0));
        contenedor.add(botonesOriginales, java.awt.BorderLayout.CENTER);
        contenedor.add(filaNueva, java.awt.BorderLayout.SOUTH);
        setContentPane(contenedor);
        pack();
        setLocationRelativeTo(null);
    }

